use py32_hal::gpio::Pin;
use py32_pac::gpio;

// ── LCD (ST7565 via HW SPI1) ────────────────────────────────────────────────
pub const LCD_A0: Pin = Pin::new(gpio::GPIOA_BASE, 6);
pub const LCD_CS: Pin = Pin::new(gpio::GPIOB_BASE, 2);

// ── BK4819 RF Transceiver (bit-bang SPI) ────────────────────────────────────
pub const BK_SCL: Pin = Pin::new(gpio::GPIOB_BASE, 8);
pub const BK_SDA: Pin = Pin::new(gpio::GPIOB_BASE, 9);
pub const BK_CSN: Pin = Pin::new(gpio::GPIOF_BASE, 9);

// ── Keyboard Matrix ─────────────────────────────────────────────────────────
pub const KB_COLS: [Pin; 4] = [
    Pin::new(gpio::GPIOB_BASE, 6),
    Pin::new(gpio::GPIOB_BASE, 5),
    Pin::new(gpio::GPIOB_BASE, 4),
    Pin::new(gpio::GPIOB_BASE, 3),
];
pub const KB_ROWS: [Pin; 4] = [
    Pin::new(gpio::GPIOB_BASE, 15),
    Pin::new(gpio::GPIOB_BASE, 14),
    Pin::new(gpio::GPIOB_BASE, 13),
    Pin::new(gpio::GPIOB_BASE, 12),
];

// ── Misc I/O ────────────────────────────────────────────────────────────────
pub const PTT: Pin = Pin::new(gpio::GPIOB_BASE, 10);
pub const AUDIO_PA: Pin = Pin::new(gpio::GPIOA_BASE, 8);

/// Voice DAC Output: GPIOA Pin 4 is the MCU's internal DAC1 Channel 1 output (`DAC1_OUT`).
/// In the Quansheng UV-K1 / K5 schematic, this net is labeled `BEEP`, but there is NO piezo
/// buzzer or speaker directly connected to this pin. Instead, it routes through an analog
/// RC filter into the LN4898 audio amplifier input for streaming 8kHz PCM voice prompts via DMA.
/// All key beeps, roger beeps, and audio tones are generated by the BK4829 RF chip's internal tone DDS.
/// When voice DAC playback is not active, PA4 is placed into Analog mode to prevent leakage.
pub const VOICE_DAC: Pin = Pin::new(gpio::GPIOA_BASE, 4);

/// Unified Backlight: Drives transistor Q29 (DTC114EE) on GPIOF Pin 8.
/// On the Quansheng UV-K1 / K5 hardware, all white front LEDs (D24, D26, D28 for LCD panel,
/// and D25, D27 for Keypad light guides) are connected in parallel to common cathode net LEDK.
/// There is NO separate keyboard backlight pin on the hardware; backlight PWM modulates both simultaneously.
pub const BACKLIGHT: Pin = Pin::new(gpio::GPIOF_BASE, 8);
pub const FLASHLIGHT: Pin = Pin::new(gpio::GPIOC_BASE, 13);
pub const FLASH_CS: Pin = Pin::new(gpio::GPIOA_BASE, 3);

// ── BK1080 Broadcast FM Radio (I2C bit-bang) ────────────────────────────────
pub const FM_SCL: Pin = Pin::new(gpio::GPIOF_BASE, 5);
pub const FM_SDA: Pin = Pin::new(gpio::GPIOF_BASE, 6);

/// Initialize all GPIO pins for the board.
pub fn init() {
    use py32_pac as pac;

    // ── Input Pins ──────────────────────────────────────────────────────
    for row in &KB_ROWS {
        row.configure_input(pac::gpio::PULL_UP);
    }
    PTT.configure_input(pac::gpio::PULL_UP);

    // ── Output Pins (high speed for keyboard columns to ensure crisp edges) ────
    for col in &KB_COLS {
        col.configure_output(pac::gpio::SPEED_HIGH);
        col.set_high(); // Idle high
    }
    AUDIO_PA.configure_output(pac::gpio::SPEED_LOW);
    FLASHLIGHT.configure_output(pac::gpio::SPEED_LOW);
    BACKLIGHT.configure_output(pac::gpio::SPEED_LOW);
    BACKLIGHT.set_low();

    // ── BK1080 I2C Pins ─────────────────────────────────────────────────
    FM_SCL.configure_output_od(pac::gpio::SPEED_LOW);
    FM_SDA.configure_output_od(pac::gpio::SPEED_LOW);
    FM_SCL.set_high();
    FM_SDA.set_high();

    // ── LCD pins ────────────────────────────────────────────────────────
    LCD_A0.configure_output(pac::gpio::SPEED_LOW);
    LCD_A0.set_high();
    LCD_CS.configure_output(pac::gpio::SPEED_LOW);
    LCD_CS.set_high(); // Deselected
    FLASH_CS.configure_output(pac::gpio::SPEED_LOW);
    FLASH_CS.set_high(); // Deselected

    // ── BK4819 pins ─────────────────────────────────────────────────────
    BK_SCL.configure_output(pac::gpio::SPEED_MEDIUM);
    BK_SDA.configure_output(pac::gpio::SPEED_LOW);
    BK_CSN.configure_output(pac::gpio::SPEED_LOW);
    BK_SCL.set_high();
    BK_SDA.set_high();
    BK_CSN.set_high();

    // ── Unused & ADC pins → analog (minimize leakage & electromagnetic pickup) ───
    py32_hal::gpio::set_pins_analog(
        pac::gpio::GPIOA_BASE,
        pac::gpio::PIN_0
            | pac::gpio::PIN_1
            | pac::gpio::PIN_2
            | pac::gpio::PIN_4
            | pac::gpio::PIN_5
            | pac::gpio::PIN_7
            | pac::gpio::PIN_15,
    );
    py32_hal::gpio::set_pins_analog(
        pac::gpio::GPIOB_BASE,
        pac::gpio::PIN_0 | pac::gpio::PIN_1 | pac::gpio::PIN_7 | pac::gpio::PIN_11,
    );
    py32_hal::gpio::set_pins_analog(
        pac::gpio::GPIOC_BASE,
        pac::gpio::PIN_0
            | pac::gpio::PIN_1
            | pac::gpio::PIN_2
            | pac::gpio::PIN_3
            | pac::gpio::PIN_4
            | pac::gpio::PIN_5
            | pac::gpio::PIN_6
            | pac::gpio::PIN_7
            | pac::gpio::PIN_8
            | pac::gpio::PIN_9
            | pac::gpio::PIN_10
            | pac::gpio::PIN_11
            | pac::gpio::PIN_12
            | pac::gpio::PIN_14
            | pac::gpio::PIN_15,
    );
    // PF7 is explicitly isolated in analog mode to prevent floating-pin gate leakage
    py32_hal::gpio::set_pins_analog(
        pac::gpio::GPIOF_BASE,
        pac::gpio::PIN_0
            | pac::gpio::PIN_1
            | pac::gpio::PIN_2
            | pac::gpio::PIN_3
            | pac::gpio::PIN_4
            | pac::gpio::PIN_7,
    );
}

/// Disables SWD debugging interface on PA13 (SWDIO) and PA14 (SWCLK) by putting them into Analog mode.
/// Eliminates leakage current and secures MCU memory against unauthorized hardware debugging extraction.
pub fn disable_swd() {
    use py32_pac as pac;
    py32_hal::gpio::set_pins_analog(pac::gpio::GPIOA_BASE, pac::gpio::PIN_13 | pac::gpio::PIN_14);
}

const STOP_PORTS: [u32; 3] = [
    py32_pac::gpio::GPIOA_BASE,
    py32_pac::gpio::GPIOB_BASE,
    py32_pac::gpio::GPIOF_BASE,
];

/// Park active peripheral and matrix GPIO pins in Analog / idle states before entering `PWR Stop`.
/// Saves the 6 `MODER`/`PUPDR` registers for ports A, B, F so `restore_from_stop()` can restore
/// exact pre-sleep pin states (including dynamic AF, DAC, and SWD settings) in ~40 bytes of code.
pub fn park_for_stop(uart_rx_wake: bool) -> [u32; 6] {
    use py32_pac::gpio as g;

    let mut saved = [0u32; 6];
    for (idx, &base) in STOP_PORTS.iter().enumerate() {
        unsafe {
            saved[idx * 2] = ((base + g::MODER_OFFSET) as *const u32).read_volatile();
            saved[idx * 2 + 1] = ((base + g::PUPDR_OFFSET) as *const u32).read_volatile();
        }
    }

    FLASHLIGHT.set_low();
    AUDIO_PA.set_low();
    BACKLIGHT.set_low();
    FLASH_CS.set_high();
    LCD_CS.set_high();
    BK_CSN.set_high();

    let mut gpioa_analog =
        g::PIN_0 | g::PIN_1 | g::PIN_2 | g::PIN_5 | g::PIN_6 | g::PIN_7 | g::PIN_9;
    if !uart_rx_wake {
        gpioa_analog |= g::PIN_10;
    } else {
        let rx = Pin::new(g::GPIOA_BASE, 10);
        rx.configure_input(g::PULL_UP);
    }
    py32_hal::gpio::set_pins_analog(g::GPIOA_BASE, gpioa_analog);

    // Park unused keypad columns/rows, BK SPI lines, and PTT in Analog to eliminate floating pull leakage.
    py32_hal::gpio::set_pins_analog(
        g::GPIOB_BASE,
        g::PIN_4
            | g::PIN_5
            | g::PIN_6
            | g::PIN_8
            | g::PIN_9
            | g::PIN_10
            | g::PIN_12
            | g::PIN_13
            | g::PIN_14,
    );

    // Park BK1080 I2C pins in Analog
    py32_hal::gpio::set_pins_analog(g::GPIOF_BASE, g::PIN_5 | g::PIN_6);

    // Arm ONLY Exit key column (PB3 low) and Row 0 (PB15 pull-up) for EXTI15 falling-edge wake.
    KB_COLS[3].configure_output(g::SPEED_LOW);
    KB_COLS[3].set_low();
    KB_ROWS[0].configure_input(g::PULL_UP);

    saved
}

/// Checks whether `KeyCode::Exit` (`PB3` -> `PB15`) is held while matrix pins are parked for STOP.
/// Distinguishes `Exit` from `Side1` (direct `PB15 -> GND`) by briefly releasing `PB3` high.
pub fn is_exit_held_parked() -> bool {
    KB_COLS[3].set_low();
    cortex_m::asm::delay(48);
    if KB_ROWS[0].is_high() {
        return false;
    }
    KB_COLS[3].set_high();
    cortex_m::asm::delay(48);
    let released_high = KB_ROWS[0].is_high();
    KB_COLS[3].set_low();
    released_high
}

/// Restore GPIO `MODER`/`PUPDR` registers and keypad idle outputs after waking from `PWR Stop`.
pub fn restore_from_stop(saved: &[u32; 6]) {
    use py32_pac::gpio as g;
    cortex_m::interrupt::free(|_| unsafe {
        for (idx, &base) in STOP_PORTS.iter().enumerate() {
            ((base + g::MODER_OFFSET) as *mut u32).write_volatile(saved[idx * 2]);
            ((base + g::PUPDR_OFFSET) as *mut u32).write_volatile(saved[idx * 2 + 1]);
        }
    });
    for col in &KB_COLS {
        col.set_high();
    }
}
