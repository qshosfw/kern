//! Host generator: prints the C SDK operation header from the compiled ABI tables.
//!
//! Usage: `abigen <out.h> [--check]`. With `--check` nothing is written; the exit
//! status is non-zero when the file on disk differs from the tables.

use abi::describe::{CAP_IDENTS, DOMAINS, SUB_GROUPS};
use std::fmt::Write;
use std::process::ExitCode;

/// `SysInfo` -> `SYS_INFO`.
fn upper_snake(name: &str) -> String {
    let mut out = String::new();
    for (i, c) in name.chars().enumerate() {
        if i > 0 && c.is_ascii_uppercase() {
            out.push('_');
        }
        out.push(c.to_ascii_uppercase());
    }
    out
}

fn render() -> String {
    let mut h = String::new();
    h.push_str("/* AUTO-GENERATED by `./kern abi` from src/abi/src/ops.rs — DO NOT EDIT. */\n");
    h.push_str("#ifndef KRX_OPS_H\n#define KRX_OPS_H\n\n");
    let mut total = 0;
    for domain in DOMAINS {
        let _ = writeln!(h, "/* Domain 0x{:X}: {} */", domain.id, domain.name);
        for op in domain.ops {
            let name = format!("OP_{}", upper_snake(op.name));
            let note = op.cap.map(|c| format!(" /* [{c}] */")).unwrap_or_default();
            let _ = writeln!(h, "#define {name:<18} 0x{:02X}u{note}", op.id);
            total += 1;
        }
        h.push('\n');
    }
    let _ = writeln!(h, "#define KRX_OP_COUNT       {total}u\n");
    h.push_str("/* Sub-opcodes (mirrored from abi::sub) */\n");
    for group in SUB_GROUPS {
        let _ = writeln!(h, "/* {} */", group.name);
        for (name, value) in group.items {
            let name = format!("SUB_{}_{name}", group.name.to_ascii_uppercase());
            let _ = writeln!(h, "#define {name:<26} {value}u");
        }
        h.push('\n');
    }
    h.push_str("/* Capabilities (abi::Cap) */\n");
    for (bit, ident) in CAP_IDENTS.iter().enumerate() {
        let name = format!("KRX_CAP_{}", upper_snake(ident));
        let _ = writeln!(h, "#define {name:<26} (1u << {bit})");
    }
    for (title, prefix, names) in [
        (
            "Built-in icon glyphs (abi::icon)",
            "KRX_ICON",
            abi::icon::NAMES,
        ),
        (
            "Properties (abi::prop): krx_prop_get / krx_prop_set",
            "KRX_PROP",
            abi::prop::NAMES,
        ),
        (
            "Declared-action scopes (abi::scope)",
            "KRX_SCOPE",
            abi::scope::NAMES,
        ),
    ] {
        let _ = writeln!(h, "\n/* {title} */");
        for (name, value) in names {
            let name = format!("{prefix}_{name}");
            let _ = writeln!(h, "#define {name:<26} {value}u");
        }
    }
    h.push_str("\n#endif /* KRX_OPS_H */\n");
    h
}

fn main() -> ExitCode {
    let mut out = None;
    let mut check = false;
    for arg in std::env::args().skip(1) {
        match arg.as_str() {
            "--check" => check = true,
            _ => out = Some(arg),
        }
    }
    let Some(out) = out else {
        eprintln!("usage: abigen <out.h> [--check]");
        return ExitCode::FAILURE;
    };
    let rendered = render();
    if check {
        if std::fs::read_to_string(&out).is_ok_and(|disk| disk == rendered) {
            println!("OK: {out} matches the ABI tables");
            return ExitCode::SUCCESS;
        }
        eprintln!("ERROR: {out} is out of sync with the ABI tables; run `./kern abi`");
        return ExitCode::FAILURE;
    }
    if let Err(e) = std::fs::write(&out, rendered) {
        eprintln!("ERROR: cannot write {out}: {e}");
        return ExitCode::FAILURE;
    }
    println!("Generated {out}");
    ExitCode::SUCCESS
}
