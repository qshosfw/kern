#!/usr/bin/env python3
"""Generate KRX C SDK operation & sub-opcode header (`packages/sdk/krx_ops.h`) from `src/kernel/src/abi.rs`.

Single source of truth: parses the declarative `abi! { ... }` and `abi_sub! { ... }` tables
in Rust and emits strictly sorted `OP_*` and `SUB_*` constants so firmware and C packages never drift.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ABI_RS = ROOT / "src" / "kernel" / "src" / "abi.rs"
OUT_H = ROOT / "packages" / "sdk" / "krx_ops.h"

DOMAIN_RE = re.compile(r"([A-Z0-9_]+)\s+(0x[0-9a-fA-F]+|\d+)\s*\{([^}]*)\}", re.S)
OP_RE = re.compile(
    r"([A-Za-z0-9_]+)\s*=\s*(\d+)\s*\(\s*([A-Za-z]+)\s*,\s*([A-Za-z]+)\s*,\s*([A-Za-z]+)\s*\)"
    r"(?:\s*\[\s*([A-Za-z0-9_]+)\s*\])?"
)
SUB_GROUP_RE = re.compile(r"([a-z0-9_]+)\s*\{([^}]*)\}", re.S)
SUB_ITEM_RE = re.compile(r"([A-Z0-9_]+)\s*=\s*(0x[0-9a-fA-F]+|\d+)")


def camel_to_upper_snake(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper()


def extract_macro_block(source: str, macro_name: str) -> str:
    """Extract the balanced `{ ... }` body of a top-level macro invocation `<macro_name>! { ... }`."""
    m = re.search(rf"(?m)^{re.escape(macro_name)}!\s*\{{", source)
    if not m:
        raise ValueError(f"Could not locate `{macro_name}! {{ ... }}` block in abi.rs")
    start = m.end()
    depth = 1
    i = start
    while i < len(source) and depth > 0:
        ch = source[i]
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
        i += 1
    if depth != 0:
        raise ValueError(f"Unbalanced braces in `{macro_name}!` block")
    return source[start : i - 1]


def parse_abi(source: str) -> list[tuple[str, int, list[tuple[str, int, str | None]]]]:
    body = extract_macro_block(source, "abi")
    domains: list[tuple[str, int, list[tuple[str, int, str | None]]]] = []
    prev_id = -1
    for dm in DOMAIN_RE.finditer(body):
        dom_name = dm.group(1)
        dom_id = int(dm.group(2), 0)
        ops: list[tuple[str, int, str | None]] = []
        for om in OP_RE.finditer(dm.group(3)):
            op_name = om.group(1)
            idx = int(om.group(2), 0)
            cap = om.group(6)
            full_id = (dom_id << 4) | idx
            if full_id <= prev_id:
                raise ValueError(
                    f"Non-monotonic op ID: {op_name} = 0x{full_id:02X} <= 0x{prev_id:02X}"
                )
            prev_id = full_id
            ops.append((op_name, full_id, cap))
        domains.append((dom_name, dom_id, ops))
    return domains


def parse_sub_ops(source: str) -> list[tuple[str, list[tuple[str, int]]]]:
    body = extract_macro_block(source, "abi_sub")
    groups: list[tuple[str, list[tuple[str, int]]]] = []
    for gm in SUB_GROUP_RE.finditer(body):
        group_name = gm.group(1)
        items: list[tuple[str, int]] = []
        seen: set[int] = set()
        for im in SUB_ITEM_RE.finditer(gm.group(2)):
            name = im.group(1)
            val = int(im.group(2), 0)
            if val in seen:
                raise ValueError(f"Duplicate sub-opcode in {group_name}: {name} = {val}")
            seen.add(val)
            items.append((name, val))
        groups.append((group_name, items))
    return groups


def render_header(
    domains: list[tuple[str, int, list[tuple[str, int, str | None]]]],
    sub_groups: list[tuple[str, list[tuple[str, int]]]],
) -> str:
    lines = [
        "/* AUTO-GENERATED by tools/gen_abi.py from src/kernel/src/abi.rs — DO NOT EDIT. */",
        "#ifndef KRX_OPS_H",
        "#define KRX_OPS_H",
        "",
    ]
    total = 0
    for dom_name, dom_id, ops in domains:
        lines.append(f"/* Domain 0x{dom_id:X}: {dom_name} */")
        for op_name, full_id, cap in ops:
            macro = f"OP_{camel_to_upper_snake(op_name)}"
            note = f" /* [{cap}] */" if cap else ""
            lines.append(f"#define {macro:<18} 0x{full_id:02X}u{note}")
            total += 1
        lines.append("")
    lines.append(f"#define KRX_OP_COUNT       {total}u")
    lines.append("")
    lines.append("/* Sub-opcodes (mirrored from kernel::abi::sub) */")
    for group_name, items in sub_groups:
        prefix = f"SUB_{group_name.upper()}"
        lines.append(f"/* {group_name} */")
        for name, val in items:
            macro = f"{prefix}_{name}"
            lines.append(f"#define {macro:<26} {val}u")
        lines.append("")
    lines.append("#endif /* KRX_OPS_H */")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--check", action="store_true", help="Fail if generated header differs from disk"
    )
    args = ap.parse_args()

    src = ABI_RS.read_text()
    domains = parse_abi(src)
    sub_groups = parse_sub_ops(src)
    rendered = render_header(domains, sub_groups)

    if args.check:
        if not OUT_H.exists() or OUT_H.read_text() != rendered:
            print(
                f"ERROR: {OUT_H.relative_to(ROOT)} is out of sync with {ABI_RS.relative_to(ROOT)}",
                file=sys.stderr,
            )
            return 1
        print(f"OK: {OUT_H.relative_to(ROOT)} matches {ABI_RS.relative_to(ROOT)}")
        return 0

    OUT_H.parent.mkdir(parents=True, exist_ok=True)
    OUT_H.write_text(rendered)
    n_ops = sum(len(d[2]) for d in domains)
    n_subs = sum(len(g[1]) for g in sub_groups)
    print(f"Generated {OUT_H.relative_to(ROOT)} ({n_ops} ops, {n_subs} sub-ops)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
