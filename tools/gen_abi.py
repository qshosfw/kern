#!/usr/bin/env python3
"""Generate KRX C SDK operation ID header (`packages/sdk/krx_ops.h`) from `src/kernel/src/abi.rs`.

Single source of truth: parses the declarative `abi! { ... }` table in Rust and emits
strictly sorted `OP_*` constants so firmware and C packages never drift.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ABI_RS = ROOT / "src" / "kernel" / "src" / "abi.rs"
OUT_H = ROOT / "packages" / "sdk" / "krx_ops.h"

DOMAIN_RE = re.compile(r"([A-Z0-9_]+)\s+(0x[0-9a-fA-F]+|\d+)\s*\{([^}]*)\}", re.S)
OP_RE = re.compile(
    r"([A-Za-z0-9_]+)\s*=\s*(\d+)\s*\(\s*([A-Za-z]+)\s*,\s*([A-Za-z]+)\s*,\s*([A-Za-z]+)\s*\)"
    r"(?:\s*\[\s*([A-Za-z0-9_]+)\s*\])?"
)


def camel_to_upper_snake(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper()


def parse_abi(source: str) -> list[tuple[str, int, list[tuple[str, int, str | None]]]]:
    m = re.search(r"abi!\s*\{(.*)\}\s*(?:#\[cfg\(test\)\]|\Z)", source, re.S)
    if not m:
        raise ValueError("Could not locate `abi! { ... }` block in abi.rs")
    body = m.group(1)
    domains: list[tuple[str, int, list[tuple[str, int, str | None]]]] = []
    prev_id = -1
    for dm in DOMAIN_RE.finditer(body):
        dom_name = dm.group(1)
        dom_id = int(dm.group(2), 0)
        ops: list[tuple[str, int, str | None]] = []
        for om in OP_RE.finditer(dm.group(3)):
            op_name = om.group(1)
            idx = int(om.group(2), 0)
            cap = om.group(6)
            full_id = (dom_id << 4) | idx
            if full_id <= prev_id:
                raise ValueError(f"Non-monotonic op ID: {op_name} = 0x{full_id:02X} <= 0x{prev_id:02X}")
            prev_id = full_id
            ops.append((op_name, full_id, cap))
        domains.append((dom_name, dom_id, ops))
    return domains


def render_header(domains: list[tuple[str, int, list[tuple[str, int, str | None]]]]) -> str:
    lines = [
        "/* AUTO-GENERATED by tools/gen_abi.py from src/kernel/src/abi.rs — DO NOT EDIT. */",
        "#ifndef KRX_OPS_H",
        "#define KRX_OPS_H",
        "",
    ]
    total = 0
    for dom_name, dom_id, ops in domains:
        lines.append(f"/* Domain 0x{dom_id:X}: {dom_name} */")
        for op_name, full_id, cap in ops:
            macro = f"OP_{camel_to_upper_snake(op_name)}"
            note = f" /* [{cap}] */" if cap else ""
            lines.append(f"#define {macro:<18} 0x{full_id:02X}u{note}")
            total += 1
        lines.append("")
    lines.append(f"#define KRX_OP_COUNT       {total}u")
    lines.append("")
    lines.append("#endif /* KRX_OPS_H */")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="Fail if generated header differs from disk")
    args = ap.parse_args()

    domains = parse_abi(ABI_RS.read_text())
    rendered = render_header(domains)

    if args.check:
        if not OUT_H.exists() or OUT_H.read_text() != rendered:
            print(f"ERROR: {OUT_H.relative_to(ROOT)} is out of sync with {ABI_RS.relative_to(ROOT)}", file=sys.stderr)
            return 1
        print(f"OK: {OUT_H.relative_to(ROOT)} matches {ABI_RS.relative_to(ROOT)}")
        return 0

    OUT_H.parent.mkdir(parents=True, exist_ok=True)
    OUT_H.write_text(rendered)
    print(f"Generated {OUT_H.relative_to(ROOT)} ({sum(len(d[2]) for d in domains)} ops)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
